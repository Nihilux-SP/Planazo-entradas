    @Bean
    CommandLineRunner initializeDatabase(JdbcTemplate jdbc) {
        return args -> {
            jdbc.execute("""
                CREATE TABLE IF NOT EXISTS events (
                    id BIGINT PRIMARY KEY, type VARCHAR(30) NOT NULL, title VARCHAR(180) NOT NULL,
                    venue VARCHAR(180) NOT NULL, city VARCHAR(80) NOT NULL, event_date VARCHAR(10) NOT NULL,
                    event_time VARCHAR(5) NOT NULL, price INTEGER NOT NULL, image VARCHAR(30) NOT NULL,
                    accent VARCHAR(20) NOT NULL, featured BOOLEAN NOT NULL
                )
                """);
            jdbc.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    email VARCHAR(254) UNIQUE NOT NULL, password_hash VARCHAR(512) NOT NULL,
                    role VARCHAR(20) NOT NULL DEFAULT 'CLIENTE', created_at TIMESTAMP NOT NULL
                )
                """);
            jdbc.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS role VARCHAR(20) NOT NULL DEFAULT 'CLIENTE'");
            jdbc.execute("""
                CREATE TABLE IF NOT EXISTS refresh_tokens (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL, token_hash VARCHAR(128) UNIQUE NOT NULL,
                    expires_at TIMESTAMP NOT NULL, revoked_at TIMESTAMP NULL,
                    FOREIGN KEY (user_id) REFERENCES users(id)
                )
                """);
            jdbc.execute("""
                CREATE TABLE IF NOT EXISTS bookings (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL, event_id BIGINT NOT NULL, quantity INTEGER NOT NULL,
                    created_at TIMESTAMP NOT NULL,
                    FOREIGN KEY (user_id) REFERENCES users(id),
                    FOREIGN KEY (event_id) REFERENCES events(id)
                )
                """);
            jdbc.execute("""
                CREATE TABLE IF NOT EXISTS favorites (
                    user_id BIGINT NOT NULL, event_id BIGINT NOT NULL, created_at TIMESTAMP NOT NULL,
                    PRIMARY KEY (user_id, event_id),
                    FOREIGN KEY (user_id) REFERENCES users(id),
                    FOREIGN KEY (event_id) REFERENCES events(id)
                )
                """);
            seedUser(jdbc, "admin@planazo.local", "AdminPlanazo2026!", "ADMIN");
            seedUser(jdbc, "gestor@planazo.local", "GestorPlanazo2026!", "GESTOR");
            seedUser(jdbc, "cliente@planazo.local", "ClientePlanazo2026!", "CLIENTE");
            for (Object[] event : SEED_EVENTS) {
                jdbc.update("""
                    INSERT INTO events (id,type,title,venue,city,event_date,event_time,price,image,accent,featured)
                    SELECT ?,?,?,?,?,?,?,?,?,?,? WHERE NOT EXISTS (SELECT 1 FROM events WHERE id=?)
                    """, event[0], event[1], event[2], event[3], event[4], event[5], event[6],
                    event[7], event[8], event[9], event[10], event[0]);
            }
        };
    }

    private void seedUser(JdbcTemplate jdbc, String email, String password, String role) {
        Integer count = jdbc.queryForObject("SELECT COUNT(*) FROM users WHERE email=?", Integer.class, email);
        if (count != null && count == 0) {
            jdbc.update("INSERT INTO users(email,password_hash,role,created_at) VALUES (?,?,?,CURRENT_TIMESTAMP)",
                email, passwordEncoder.encode(password), role);
        }
    }
